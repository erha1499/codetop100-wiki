def fn(name, cases, unordered=None):
    """unordered: 'outer' 忽略最外层顺序；'deep' 连内层顺序也忽略。"""
    return {"kind": "fn", "name": name, "cases": cases, "unordered": unordered}


def design(cls, ops, args, expected):
    return {"kind": "design", "cls": cls, "ops": ops, "args": args, "expected": expected}


def custom(need, cases):
    return {"kind": "custom", "need": need, "cases": cases}


def grid(*rows):
    return [list(r) for r in rows]


def jv(vals):
    return ",".join("null" if v is None else str(v) for v in vals)


def lca(vals, p, q, want):
    return (
        lambda ns, h: (lambda r: ns["Solution"]().lowestCommonAncestor(r, h.find(r, p), h.find(r, q)).val)(h.tree(*vals)),
        f"TreeNode r = H.tree({jv(vals)}); return new Solution().lowestCommonAncestor(r, H.find(r, {p}), H.find(r, {q})).val;",
        want,
    )


def cycle(method, pos, vals, want, node=False):
    """成环链表：尾节点接到下标 pos（-1 表示无环）。node=True 时方法返回节点，比较它的值。"""
    v = ",".join(map(str, vals))
    if node:
        return (
            lambda ns, h: (lambda r: r.val if r else None)(getattr(ns["Solution"](), method)(h.cycle(pos, *vals))),
            f"ListNode r = new Solution().{method}(H.cycle({pos}{',' + v if v else ''})); return r == null ? null : r.val;",
            want,
        )
    return (
        lambda ns, h: getattr(ns["Solution"](), method)(h.cycle(pos, *vals)),
        f"return new Solution().{method}(H.cycle({pos}{',' + v if v else ''}));",
        want,
    )


def intersect(a, b, common, want):
    """两条链表 a、b 后面接同一段 common。"""
    ja, jb, jc = (",".join(map(str, x)) for x in (a, b, common))
    return (
        lambda ns, h: (lambda c: (lambda r: r.val if r else None)(
            ns["Solution"]().getIntersectionNode(h.join(h.list(*a), c), h.join(h.list(*b), c))))(h.list(*common)),
        f"ListNode c = H.list({jc}); ListNode r = new Solution().getIntersectionNode("
        f"H.join(H.list({ja}), c), H.join(H.list({jb}), c)); return r == null ? null : r.val;",
        want,
    )


